#!/usr/bin/env python3
"""暴走族「10万人比」時系列の算出（JON-64 P3 率の実数化）。
分子: 警察庁 令和7年白書 5-27(勢力)/5-28(検挙)。分母: 総務省人口推計 15-24歳総人口(千人)。
依存ゼロ（標準ライブラリのみ）。`python3 compute_rate.py` で再現。"""

# --- 分子（警察庁 令和7年警察白書、単位=人） ---
kyodo  = {2020: 4505, 2021: 4679, 2022: 4581, 2023: 4579, 2024: 4483}  # 5-27 共同危険型 勢力
ihou   = {2020: 1209, 2021: 1159, 2022: 1189, 2023: 1271, 2024: 1397}  # 5-27 違法競走型 勢力
kenkyo = {2020: 580,  2021: 533,  2022: 526,  2023: 402,  2024: 365}   # 5-28 うち共同危険行為 検挙人員

# --- 分母（総務省 人口推計 各年10/1 総人口、単位=千人） ---
pop15_19 = {2020: 5706, 2021: 5580, 2022: 5512, 2023: 5494, 2024: 5457}
pop20_24 = {2020: 6320, 2021: 6263, 2022: 6263, 2023: 6236, 2024: 6260}
pop_k = {y: pop15_19[y] + pop20_24[y] for y in pop15_19}  # 15-24歳 計（千人）

def per100k(num, y):
    # num(人) / (pop_k千人 * 1000人) * 100000 = num / pop_k * 100
    return num / pop_k[y] * 100

def pct(d):
    a, b = d[2020], d[2024]
    return (b - a) / a * 100

sei = {y: kyodo[y] + ihou[y] for y in pop_k}

print("year | 15-24人口(千) | 勢力合計 /10万 | 共同危険型 /10万 | 違法競走型 /10万 | 共危検挙 /10万")
for y in sorted(pop_k):
    print(f"{y} | {pop_k[y]:6d} | {sei[y]} {per100k(sei[y],y):6.2f} | "
          f"{kyodo[y]} {per100k(kyodo[y],y):6.2f} | {ihou[y]} {per100k(ihou[y],y):6.2f} | "
          f"{kenkyo[y]} {per100k(kenkyo[y],y):6.3f}")

print("\n2020->2024 率(10万人比)変化:")
for name, d in [("勢力合計", sei), ("共同危険型勢力", kyodo),
                ("違法競走型勢力", ihou), ("共同危険行為検挙", kenkyo)]:
    r20, r24 = per100k(d[2020], 2020), per100k(d[2024], 2024)
    print(f"  {name}: {r20:.2f} -> {r24:.2f}  ({(r24-r20)/r20*100:+.1f}%)  [絶対 {pct(d):+.1f}%]")
print(f"  15-24歳人口(千): {pop_k[2020]} -> {pop_k[2024]}  ({pct(pop_k):+.1f}%)")
